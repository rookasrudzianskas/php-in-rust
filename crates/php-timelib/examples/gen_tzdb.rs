//! Generator for the bundled timezone database asset and the abbreviation table.
//!
//! PHP ships its own copy of the IANA database inside `ext/date/lib/timezonedb.h`
//! (a C array of TZif-like blobs plus a sorted index). This tool converts the
//! *slim* variant of that header (the one compiled into php-src, because
//! `parse_tz.c` defines `TIMELIB_SUPPORT_SLIM_FILE`) into `data/tzdb.bin`, and
//! converts `timezonemap.h` + `fallbackmap.h` into `src/tz/abbr_data.rs`.
//!
//! Regenerate with:
//!
//! ```text
//! cargo run -p php-timelib --example gen_tzdb -- \
//!     php-src-ref/ext/date/lib crates/php-timelib
//! ```
//!
//! `data/tzdb.bin` layout (all integers big-endian):
//!
//! ```text
//! b"PHPTZDB1"
//! u16 version length, version bytes (e.g. "2026.5")
//! u32 index entry count
//!   per entry: u8 id length, id bytes, u32 offset into the data blob
//! u32 data length, data bytes (identical to timelib_timezone_db_data_builtin)
//! ```

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: gen_tzdb <php-src/ext/date/lib> <crates/php-timelib>");
        std::process::exit(2);
    }
    let lib = Path::new(&args[1]);
    let out = Path::new(&args[2]);

    let header = fs::read_to_string(lib.join("timezonedb.h")).expect("read timezonedb.h");
    let (version, index, data) = parse_timezonedb(&header);
    let mut bin = Vec::with_capacity(data.len() + index.len() * 32);
    bin.extend_from_slice(b"PHPTZDB1");
    bin.extend_from_slice(&(version.len() as u16).to_be_bytes());
    bin.extend_from_slice(version.as_bytes());
    bin.extend_from_slice(&(index.len() as u32).to_be_bytes());
    for (id, pos) in &index {
        bin.push(u8::try_from(id.len()).expect("id too long"));
        bin.extend_from_slice(id.as_bytes());
        bin.extend_from_slice(&pos.to_be_bytes());
    }
    bin.extend_from_slice(&(data.len() as u32).to_be_bytes());
    bin.extend_from_slice(&data);
    fs::write(out.join("data/tzdb.bin"), &bin).expect("write tzdb.bin");
    eprintln!(
        "tzdb.bin: version {version}, {} zones, {} data bytes",
        index.len(),
        data.len()
    );

    let map = fs::read_to_string(lib.join("timezonemap.h")).expect("read timezonemap.h");
    let fallback = fs::read_to_string(lib.join("fallbackmap.h")).expect("read fallbackmap.h");
    let mut rs = String::new();
    rs.push_str("// @generated by `examples/gen_tzdb.rs` from timezonemap.h and fallbackmap.h.\n");
    rs.push_str("// Do not edit by hand.\n\n");
    rs.push_str("use super::abbr::TzLookupEntry;\n\n");
    write_table(&mut rs, "TIMEZONE_MAP", &map);
    write_table(&mut rs, "FALLBACK_MAP", &fallback);
    fs::write(out.join("src/tz/abbr_data.rs"), rs).expect("write abbr_data.rs");
}

/// Extracts the slim index + data arrays (the first `#ifdef` branch).
fn parse_timezonedb(header: &str) -> (String, Vec<(String, u32)>, Vec<u8>) {
    let slim_start = header
        .find("#ifdef TIMELIB_SUPPORT_SLIM_FILE")
        .expect("slim section");
    let slim_end = header[slim_start..].find("#else").expect("#else") + slim_start;
    let slim = &header[slim_start..slim_end];

    let idx_start = slim.find("timezonedb_idx_builtin").expect("index");
    let idx_body_start = slim[idx_start..].find('{').unwrap() + idx_start + 1;
    let idx_body_end = slim[idx_body_start..].find("};").unwrap() + idx_body_start;
    let mut index = Vec::new();
    for line in slim[idx_body_start..idx_body_end].lines() {
        let line = line.trim();
        if !line.starts_with('{') {
            continue;
        }
        let q1 = line.find('"').unwrap();
        let q2 = line[q1 + 1..].find('"').unwrap() + q1 + 1;
        let id = line[q1 + 1..q2].to_string();
        let hex = line[q2..].find("0x").unwrap() + q2 + 2;
        let hex_end = line[hex..].find(|c: char| !c.is_ascii_hexdigit()).unwrap() + hex;
        let pos = u32::from_str_radix(&line[hex..hex_end], 16).unwrap();
        index.push((id, pos));
    }

    let data_start = slim.find("timelib_timezone_db_data_builtin").expect("data");
    let decl_len_start = slim[data_start..].find('[').unwrap() + data_start + 1;
    let decl_len_end = slim[decl_len_start..].find(']').unwrap() + decl_len_start;
    let declared: usize = slim[decl_len_start..decl_len_end].parse().unwrap();
    let body_start = slim[data_start..].find('{').unwrap() + data_start + 1;
    let body_end = slim[body_start..].find("};").unwrap() + body_start;
    let mut data = Vec::with_capacity(declared);
    let mut body = &slim[body_start..body_end];
    while let Some(p) = body.find("0x") {
        let b = u8::from_str_radix(&body[p + 2..p + 4], 16).unwrap();
        data.push(b);
        body = &body[p + 4..];
    }
    assert_eq!(data.len(), declared, "data length mismatch");

    let ver_pos = header.find("timezonedb_builtin = {").expect("version");
    let v1 = header[ver_pos..].find('"').unwrap() + ver_pos + 1;
    let v2 = header[v1..].find('"').unwrap() + v1;
    (header[v1..v2].to_string(), index, data)
}

fn write_table(rs: &mut String, name: &str, src: &str) {
    let mut rows = Vec::new();
    for line in src.lines() {
        let line = line.trim();
        if !line.starts_with('{') {
            continue;
        }
        let inner = line.trim_start_matches('{').trim_end_matches(',');
        let inner = inner.trim_end().trim_end_matches('}');
        let parts: Vec<&str> = inner.split(',').map(str::trim).collect();
        assert_eq!(parts.len(), 4, "bad line: {line}");
        let abbr = parts[0].trim_matches('"');
        let dst: i32 = parts[1].parse().unwrap();
        let offset = eval_product(parts[2]);
        let id = match parts[3] {
            "NULL" => None,
            quoted => Some(quoted.trim_matches('"').to_string()),
        };
        rows.push((abbr.to_string(), dst, offset, id));
    }
    let _ = writeln!(rs, "pub(crate) static {name}: &[TzLookupEntry] = &[");
    for (abbr, dst, offset, id) in rows {
        let _ = writeln!(
            rs,
            "    TzLookupEntry {{ name: {abbr:?}, dst: {}, gmtoffset: {offset}, full_tz_name: {id:?} }},",
            dst != 0
        );
    }
    rs.push_str("];\n\n");
}

/// Evaluates `"-660 * 60"` style constant expressions used in fallbackmap.h.
fn eval_product(expr: &str) -> i32 {
    expr.split('*')
        .map(|p| p.trim().parse::<i32>().unwrap())
        .product()
}
