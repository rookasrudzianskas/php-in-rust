fn incremental(algo: &str, data: &[u8], chunk: usize) -> String {
    let mut h = new_hasher(algo, &HashOptions::none()).expect("known algorithm");
    for piece in data.chunks(chunk.max(1)) {
        h.update(piece);
    }
    to_hex(&h.finalize())
}

#[test]
fn phpt_vectors() {
    let mut failures = Vec::new();
    for (algo, input, expected) in VECTORS {
        let data = input.data();
        let got = hash(algo, &data)
            .map(|d| to_hex(&d))
            .unwrap_or_else(|e| format!("error: {e}"));
        if got != *expected {
            failures.push(format!(
                "{algo}: len {} expected {expected} got {got}",
                data.len()
            ));
            continue;
        }
        // Only the shorter inputs are re-run with awkward chunk sizes.
        if data.len() <= 20_000 {
            for chunk in [1, 3, 17, 63, 64, 65, 127, 128, 129, 1000] {
                let got = incremental(algo, &data, chunk);
                if got != *expected {
                    failures.push(format!(
                        "{algo}: chunk {chunk} len {} got {got}",
                        data.len()
                    ));
                }
            }
        } else {
            let got = incremental(algo, &data, 4999);
            if got != *expected {
                failures.push(format!("{algo}: chunk 4999 len {} got {got}", data.len()));
            }
        }
        // hash_copy(): a clone taken mid-stream finishes identically.
        let mut h = new_hasher(algo, &HashOptions::none()).unwrap();
        let split = data.len() / 3;
        h.update(&data[..split]);
        let mut copy = h.clone();
        h.update(&data[split..]);
        copy.update(&data[split..]);
        if to_hex(&h.finalize()) != *expected || to_hex(&copy.finalize()) != *expected {
            failures.push(format!("{algo}: clone mismatch len {}", data.len()));
        }
    }
    assert!(
        failures.is_empty(),
        "{} failures:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
