//! SHA3-224, SHA3-256, SHA3-384 and SHA3-512 (Keccak-f[1600] sponge).

use crate::hasher::{Engine, load_le64, read_le64};
use crate::state::{StateResult, Visitor};

/// `magic` PHP writes for Keccak contexts built from the 64-bit XKCP backend.
const MAGIC_KECCAK_64: i64 = 100;

/// Lanes XKCP's "lane complementing" backend stores inverted.
const COMPLEMENTED_LANES: [usize; 6] = [1, 2, 8, 12, 17, 20];

/// Lane visited by step `t` of the combined rho/pi walk, and its rotation offset.
const fn rho_pi_tables() -> ([usize; 24], [u32; 24]) {
    let mut lanes = [0usize; 24];
    let mut rotations = [0u32; 24];
    let (mut x, mut y) = (1usize, 0usize);
    let mut t = 0;
    while t < 24 {
        rotations[t] = (((t + 1) * (t + 2) / 2) % 64) as u32;
        let next_y = (2 * x + 3 * y) % 5;
        x = y;
        y = next_y;
        lanes[t] = x + 5 * y;
        t += 1;
    }
    (lanes, rotations)
}

/// Round constants, generated by the degree-8 LFSR of the Keccak specification.
const fn round_constants() -> [u64; 24] {
    let mut rc = [0u64; 24];
    let mut lfsr: u8 = 0x01;
    let mut round = 0;
    while round < 24 {
        let mut j = 0;
        while j < 7 {
            let bit = lfsr & 0x01 != 0;
            lfsr = if lfsr & 0x80 != 0 {
                (lfsr << 1) ^ 0x71
            } else {
                lfsr << 1
            };
            if bit {
                rc[round] ^= 1u64 << ((1u32 << j) - 1);
            }
            j += 1;
        }
        round += 1;
    }
    rc
}

const PI_LANES: [usize; 24] = rho_pi_tables().0;
const RHO_OFFSETS: [u32; 24] = rho_pi_tables().1;
const ROUND_CONSTANTS: [u64; 24] = round_constants();

/// Keccak-f[1600] with 24 rounds (lane `x + 5 * y`).
fn keccak_f(a: &mut [u64; 25]) {
    for rc in ROUND_CONSTANTS {
        // Theta
        let mut c = [0u64; 5];
        for (x, cx) in c.iter_mut().enumerate() {
            *cx = a[x] ^ a[x + 5] ^ a[x + 10] ^ a[x + 15] ^ a[x + 20];
        }
        for x in 0..5 {
            let d = c[(x + 4) % 5] ^ c[(x + 1) % 5].rotate_left(1);
            for y in 0..5 {
                a[x + 5 * y] ^= d;
            }
        }
        // Rho and Pi
        let mut current = a[1];
        for (&lane, &rotation) in PI_LANES.iter().zip(&RHO_OFFSETS) {
            let temp = a[lane];
            a[lane] = current.rotate_left(rotation);
            current = temp;
        }
        // Chi
        for y in 0..5 {
            let row: [u64; 5] = std::array::from_fn(|x| a[x + 5 * y]);
            for x in 0..5 {
                a[x + 5 * y] = row[x] ^ (!row[(x + 1) % 5] & row[(x + 2) % 5]);
            }
        }
        // Iota
        a[0] ^= rc;
    }
}

/// SHA-3 sponge with a fixed rate.
#[derive(Clone)]
pub(crate) struct Sha3 {
    lanes: [u64; 25],
    /// Rate in bytes (`(1600 - 2 * bits) / 8`).
    rate: usize,
    /// Number of bytes of the current block already absorbed (`byteIOIndex`).
    index: usize,
    digest_len: usize,
}

impl Sha3 {
    pub(crate) fn new(bits: usize) -> Self {
        Self {
            lanes: [0; 25],
            rate: (1600 - 2 * bits) / 8,
            index: 0,
            digest_len: bits / 8,
        }
    }

    fn xor_byte(&mut self, pos: usize, byte: u8) {
        self.lanes[pos / 8] ^= u64::from(byte) << (8 * (pos % 8));
    }

    fn state_bytes(&self) -> [u8; 200] {
        let mut out = [0u8; 200];
        for (i, lane) in self.lanes.iter().enumerate() {
            let stored = if COMPLEMENTED_LANES.contains(&i) {
                !lane
            } else {
                *lane
            };
            out[i * 8..i * 8 + 8].copy_from_slice(&stored.to_le_bytes());
        }
        out
    }

    fn load_state_bytes(&mut self, bytes: &[u8; 200]) {
        let words = load_le64::<25>(bytes);
        for (i, stored) in words.into_iter().enumerate() {
            self.lanes[i] = if COMPLEMENTED_LANES.contains(&i) {
                !stored
            } else {
                stored
            };
        }
    }
}

impl Engine for Sha3 {
    const MAGIC: Option<i64> = Some(MAGIC_KECCAK_64);

    fn update(&mut self, data: &[u8]) {
        let mut data = data;
        while !data.is_empty() {
            if self.index == 0 && data.len() >= self.rate {
                // Whole blocks straight into the state.
                let (block, rest) = data.split_at(self.rate);
                for (i, lane) in self.lanes.iter_mut().take(self.rate / 8).enumerate() {
                    *lane ^= read_le64(block, i);
                }
                keccak_f(&mut self.lanes);
                data = rest;
            } else {
                let n = data.len().min(self.rate - self.index);
                for (k, &b) in data[..n].iter().enumerate() {
                    self.xor_byte(self.index + k, b);
                }
                self.index += n;
                data = &data[n..];
                if self.index == self.rate {
                    keccak_f(&mut self.lanes);
                    self.index = 0;
                }
            }
        }
    }

    fn finish(mut self) -> Vec<u8> {
        self.xor_byte(self.index, 0x06);
        self.xor_byte(self.rate - 1, 0x80);
        keccak_f(&mut self.lanes);
        let mut out: Vec<u8> = self.lanes.iter().flat_map(|l| l.to_le_bytes()).collect();
        out.truncate(self.digest_len);
        out
    }

    fn visit(&mut self, v: &mut dyn Visitor) -> StateResult {
        // "b200IiIIB": the Keccak_HashInstance of XKCP.
        let mut bytes = self.state_bytes();
        v.bytes(&mut bytes)?;
        self.load_state_bytes(&bytes);
        v.skip(4, 4); // rate
        let mut index = self.index as u64;
        v.scalar(4, &mut index)?; // byteIOIndex
        self.index = index as usize;
        v.skip(4, 4); // squeezing
        v.skip(4, 4); // fixedOutputLength
        v.skip(1, 1); // delimitedSuffix
        Ok(())
    }

    fn validate(&self) -> bool {
        self.index < self.rate
    }
}
