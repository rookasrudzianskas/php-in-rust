/// The token kind named `name` (`T_DOUBLE_COLON` is an alias of
/// `T_PAAMAYIM_NEKUDOTAYIM`).
pub fn kind_by_name(name: &str) -> Option<TokenKind> {
    if name == "T_DOUBLE_COLON" {
        return Some(TokenKind::PaamayimNekudotayim);
    }
    TokenKind::ALL
        .iter()
        .copied()
        .find(|k| k.name() == Some(name))
}

/// `get_token_type_name()`: the `T_*` name of a token id, `None` for ids that
/// are not named tokens of the grammar (single characters, `END`, `T_ERROR`).
pub fn get_token_type_name(id: i32) -> Option<&'static str> {
    let kind = TokenKind::from_id(u16::try_from(id).ok()?)?;
    if kind == TokenKind::Error {
        return None;
    }
    kind.name()
        .filter(|n| n.starts_with("T_"))
        .map(|_| kind.token_name())
}
