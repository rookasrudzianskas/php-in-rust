#[cfg(test)]
mod tests {
    use super::state_to_description;

    #[test]
    fn known_states() {
        assert_eq!(state_to_description(b"HY000"), Some("General error"));
        assert_eq!(state_to_description(b"00000"), Some("No error"));
        assert_eq!(
            state_to_description(b"HY093"),
            Some("Invalid parameter number")
        );
        assert_eq!(
            state_to_description(b"IM001"),
            Some("Driver does not support this function")
        );
        assert_eq!(
            state_to_description(b"23000"),
            Some("Integrity constraint violation")
        );
        assert_eq!(state_to_description(b"XXXXX"), None);
    }
}
