#!/usr/bin/env python3
"""Generate tables.rs (the data of html.c) from php-src's ext/standard/html_tables.h.

html_tables.h is itself generated by php-src's html_tables/html_table_gen.php; it is the
ground truth used here. Usage (from the repository root):

    python3 -I crates/php-ext/src/standard/html/gen_tables.py \
        <php-src>/ext/standard/html_tables.h > crates/php-ext/src/standard/html/tables.rs
    rustfmt --edition 2024 crates/php-ext/src/standard/html/tables.rs

The layout mirrors the C one:
* charset name map (`charset_map`) and the `LONGEST_*` constants;
* single-byte charset -> Unicode tables (`enc_to_uni_*`), flattened to 256 entries;
* Unicode -> single-byte charset tables (`unimap_*`), sorted by code point;
* code point -> entity multi-stage tables (`entity_ms_table_html5`/`_html4`): stage 1 and
  stage 2 hold indices of deduplicated blocks (index 0 is the empty block);
* the 64-entry basic entity tables (`stage3_table_be_{apos,noapos}_00000`);
* entity -> code point maps (`ent_ht_*`) as arrays sorted by name for binary search instead
  of the C hash tables (each hash bucket is checked against `zend_inline_hash_func`).
"""

import re
import sys

# C `enum entity_charset` member -> Rust `Charset` variant (same order as the C enum).
CHARSETS = {
    "cs_utf_8": "Utf8",
    "cs_8859_1": "Iso8859_1",
    "cs_cp1252": "Cp1252",
    "cs_8859_15": "Iso8859_15",
    "cs_cp1251": "Cp1251",
    "cs_8859_5": "Iso8859_5",
    "cs_cp866": "Cp866",
    "cs_macroman": "MacRoman",
    "cs_koi8r": "Koi8R",
    "cs_big5": "Big5",
    "cs_gb2312": "Gb2312",
    "cs_big5hkscs": "Big5Hkscs",
    "cs_sjis": "Sjis",
    "cs_eucjp": "EucJp",
}


def fail(msg):
    sys.exit("gen_tables.py: " + msg)


def cint(s):
    """Parses a C integer literal (hex or decimal; the octal 01/02 of the C file are < 8)."""
    s = s.strip()
    if s.lower().startswith("0x"):
        return int(s, 16)
    return int(s, 10)


def zend_inline_hash(name):
    h = 5381
    for b in name.encode("ascii"):
        h = (h * 33 + b) & 0xFFFFFFFFFFFFFFFF
    return h | 0x8000000000000000


def body_of(src, decl):
    """Returns the initializer text of the C declaration whose header is `decl`."""
    m = re.search(re.escape(decl) + r"\s*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        fail("declaration not found: " + decl)
    return m.group(1)


def items(body):
    return [p.strip() for p in body.split(",") if p.strip()]


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        fail("usage: gen_tables.py <php-src>/ext/standard/html_tables.h")
    with open(sys.argv[1], encoding="utf-8") as f:
        src = f.read()
    # Comments carry no data; entity names never contain "/*".
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)

    out = []
    w = out.append

    # ----- charsets ---------------------------------------------------------------------
    m = re.search(r"enum entity_charset \{(.*?)\};", src, re.S)
    enum = items(m.group(1))
    if enum[-1] != "cs_numelems" or enum[:-1] != list(CHARSETS):
        fail("unexpected enum entity_charset: %r" % enum)
    enum = enum[:-1]

    cmap = re.findall(
        r'\{\s*"([^"]+)",\s*sizeof\("([^"]+)"\)-1,\s*(cs_\w+)\s*\}',
        body_of(src, "} charset_map[]"),
    )
    if not cmap:
        fail("charset_map not found")
    for name, name2, cs in cmap:
        if name != name2 or name != name.lower() or cs not in CHARSETS:
            fail("bad charset_map entry " + name)

    def define(name):
        m = re.search(r"#define " + name + r"\s+(\d+)", src)
        if not m:
            fail("missing #define " + name)
        return int(m.group(1))

    longest_codeset = define("LONGEST_CODESET_LENGTH")
    longest_entity = define("LONGEST_ENTITY_LENGTH")
    if longest_codeset != max(len(n) for n, _, _ in cmap):
        fail("LONGEST_CODESET_LENGTH mismatch")

    w("// Entity and charset tables of ext/standard/html.c.")
    w("//")
    w("// @generated by crates/php-ext/src/standard/html/gen_tables.py from php-src's")
    w("// ext/standard/html_tables.h -- DO NOT EDIT. Regenerate with")
    w("//   python3 -I crates/php-ext/src/standard/html/gen_tables.py \\")
    w("//       <php-src>/ext/standard/html_tables.h > crates/php-ext/src/standard/html/tables.rs")
    w("//   rustfmt --edition 2024 crates/php-ext/src/standard/html/tables.rs")
    w("")
    w("use super::charset::Charset;")
    w("use super::entity::EntRow::{Empty as E, Multi as M, One as O};")
    w("use super::entity::{EntRow, MsTable, MultiCp, NamedEntity};")
    w("")
    w("/// Number of supported charsets (`cs_numelems`).")
    w("pub const CHARSET_COUNT: usize = %d;" % len(enum))
    w("")
    w("/// Length of the longest codeset name of [`CHARSET_MAP`].")
    w("pub const LONGEST_CODESET_LENGTH: usize = %d;" % longest_codeset)
    w("")
    w("/// Longest entity name length, excluding `&` and `;`.")
    w("pub const LONGEST_ENTITY_LENGTH: usize = %d;" % longest_entity)
    w("")
    w("/// Lowercase charset names and aliases (`charset_map`); UTF-8 is not in the map.")
    w("pub static CHARSET_MAP: [(&str, Charset); %d] = [" % len(cmap))
    for name, _, cs in cmap:
        w("    (%s, Charset::%s)," % (rust_str(name), CHARSETS[cs]))
    w("];")
    w("")

    # ----- single-byte charset -> Unicode -------------------------------------------------
    s2 = {}
    for name, body in re.findall(r"static const enc_to_uni_stage2 (\w+) = \{ \{(.*?)\} \};", src, re.S):
        vals = [cint(v) for v in items(body)]
        if len(vals) != 64:
            fail("stage 2 table %s has %d entries" % (name, len(vals)))
        s2[name] = vals
    s1 = {}
    for name, body in re.findall(r"static const enc_to_uni (\w+) = \{ \{(.*?)\}\s*\};", src, re.S):
        parts = [p.lstrip("&") for p in items(body)]
        if len(parts) != 4:
            fail("stage 1 table %s has %d entries" % (name, len(parts)))
        s1[name] = [v for p in parts for v in s2[p]]
    index = items(body_of(src, "static const enc_to_uni *const enc_to_uni_index[cs_numelems]"))
    index += ["NULL"] * (len(enum) - len(index))
    w("/// Single-byte charset -> Unicode (`enc_to_uni_index`, the C two-stage tables")
    w("/// flattened), indexed by `Charset as usize`. 0xFFFF marks a byte without mapping.")
    w("pub static ENC_TO_UNI: [Option<&[u16; 256]>; CHARSET_COUNT] = [")
    for cs, p in zip(enum, index):
        if p == "NULL":
            w("    None, // %s" % cs)
        else:
            w("    Some(&%s), // %s" % (p.lstrip("&").upper(), cs))
    w("];")
    w("")
    for name in sorted(s1):
        w("static %s: [u16; 256] = [" % name.upper())
        w("    " + ", ".join("0x%04X" % v for v in s1[name]) + ",")
        w("];")
        w("")

    # ----- Unicode -> single-byte charset -------------------------------------------------
    for name, body in re.findall(r"static const uni_to_enc (\w+)\[\] = \{(.*?)\n\};", src, re.S):
        rows = [
            (cint(a), cint(b))
            for a, b in re.findall(r"\{\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+)\s*\}", body)
        ]
        if [r[0] for r in rows] != sorted({r[0] for r in rows}):
            fail(name + " is not sorted")
        w("/// Unicode -> charset byte (`%s`), sorted by code point." % name)
        w("pub static %s: [(u16, u8); %d] = [" % (name.upper(), len(rows)))
        w("    " + ", ".join("(0x%04X, 0x%02X)" % r for r in rows) + ",")
        w("];")
        w("")

    # ----- code point -> entity -------------------------------------------------------------
    multi = {}
    for name, body in re.findall(r"static const entity_multicodepoint_row (\w+)\[\] = \{(.*?)\n\};", src, re.S):
        rows = re.findall(r'\{ \{(NULL|"[^"]*"),\s*(\w+),\s*(\d+)\} \}', body)
        default, size, dlen = rows[0]
        if cint(size) != len(rows) - 1:
            fail("bad size in " + name)
        default = None if default == "NULL" else default.strip('"')
        if int(dlen) != (len(default) if default else 0):
            fail("bad default length in " + name)
        rest = []
        for ent, cp, ln in rows[1:]:
            ent = ent.strip('"')
            if int(ln) != len(ent):
                fail("bad entity length in " + name)
            rest.append((cint(cp), ent))
        multi[name] = (default, rest)

    stage3 = {}
    for name, body in re.findall(r"static const entity_stage3_row (\w+)\[\] = \{(.*?)\n\};", src, re.S):
        rows = re.findall(r'\{([01]), \{ \{(NULL|"[^"]*"|\(void \*\)\w+), (\d+)\} \} \}', body)
        if len(rows) != 64:
            fail("stage 3 table %s has %d rows" % (name, len(rows)))
        conv = []
        for amb, val, ln in rows:
            if amb == "1":
                conv.append(("multi", multi[val[len("(void *)") :]]))
            elif val == "NULL":
                conv.append(None)
            else:
                ent = val.strip('"')
                if int(ln) != len(ent):
                    fail("bad entity length in " + name)
                conv.append(("one", ent))
        stage3[name] = conv

    stage2 = {}
    for name, body in re.findall(r"static const entity_stage2_row (\w+)\[\] = \{(.*?)\};", src, re.S):
        parts = items(body)
        if len(parts) != 64:
            fail("stage 2 table %s has %d entries" % (name, len(parts)))
        stage2[name] = parts

    def row_code(r):
        if r is None:
            return "E"
        if r[0] == "one":
            return "O(%s)" % rust_str(r[1])
        default, rest = r[1]
        return "M(&MultiCp { default: %s, rest: &[%s] })" % (
            "Some(%s)" % rust_str(default) if default else "None",
            ", ".join("(0x%05X, %s)" % (cp, rust_str(e)) for cp, e in rest),
        )

    for tbl, rust_name, doc in (
        ("html5", "HTML5", "HTML5 (`entity_ms_table_html5`)"),
        ("html4", "HTML4", "HTML 4.01 (`entity_ms_table_html4`)"),
    ):
        s1names = items(body_of(src, "static const entity_stage1_row entity_ms_table_%s[]" % tbl))
        if len(s1names) != 0x1E:
            fail("stage 1 table of %s has %d entries" % (tbl, len(s1names)))
        s2_ids = ["empty_stage2_table"]
        s3_ids = ["empty_stage3_table"]
        for n in s1names:
            if n not in s2_ids:
                s2_ids.append(n)
        for n in s2_ids:
            for p in stage2[n]:
                if p not in s3_ids:
                    s3_ids.append(p)
        if len(s2_ids) > 256 or len(s3_ids) > 256:
            fail("too many blocks for u8 indices")
        if any(r is not None for r in stage3["empty_stage3_table"]):
            fail("empty_stage3_table is not empty")
        w("/// Code point -> entity table for %s." % doc)
        w("pub static %s: MsTable = MsTable {" % rust_name)
        w("    stage1: [%s]," % ", ".join(str(s2_ids.index(n)) for n in s1names))
        w("    stage2: &%s_STAGE2," % rust_name)
        w("    stage3: &%s_STAGE3," % rust_name)
        w("};")
        w("")
        w("static %s_STAGE2: [[u8; 64]; %d] = [" % (rust_name, len(s2_ids)))
        for n in s2_ids:
            w("    // %s" % n)
            w("    [%s]," % ", ".join(str(s3_ids.index(p)) for p in stage2[n]))
        w("];")
        w("")
        w("#[rustfmt::skip]")
        w("static %s_STAGE3: [[EntRow; 64]; %d] = [" % (rust_name, len(s3_ids)))
        for n in s3_ids:
            if n == "empty_stage3_table":
                w("    // empty_stage3_table")
                w("    [E; 64],")
                continue
            base = int(n.rsplit("_", 1)[1], 16)
            w("    // %s: U+%04X..U+%04X" % (n, base, base + 63))
            w("    [")
            line = []
            for i, r in enumerate(stage3[n]):
                if r is not None and r[0] == "multi":
                    # two-code-point rows get a line of their own
                    if line:
                        w("        " + " ".join(line))
                        line = []
                    w("        %s, // U+%04X" % (row_code(r), base + i))
                else:
                    line.append(row_code(r) + ",")
                if i % 8 == 7 and line:
                    w("        " + " ".join(line))
                    line = []
            w("    ],")
        w("];")
        w("")

    for tbl, rust_name, doc in (
        ("be_noapos", "BASIC_NOAPOS", "basic entities without `&apos;`"),
        ("be_apos", "BASIC_APOS", "basic entities with `&apos;`"),
    ):
        rows = stage3["stage3_table_%s_00000" % tbl]
        if any(r is not None and r[0] != "one" for r in rows):
            fail("ambiguous row in basic table " + tbl)
        w("/// Code point (< 64) -> entity for %s (`stage3_table_%s_00000`)." % (doc, tbl))
        w("pub static %s: [Option<&str>; 64] = [" % rust_name)
        w("    " + " ".join(("None," if r is None else "Some(%s)," % rust_str(r[1])) for r in rows))
        w("];")
        w("")

    # ----- entity -> code point -------------------------------------------------------------
    buckets = {}
    for name, body in re.findall(r"static const entity_cp_map (\w+)\[\] = \{(.*?)\};\n", src):
        rows = re.findall(r'\{"([^"]+)", (\d+), (0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+|0)\}', body)
        for ent, ln, _, _ in rows:
            if int(ln) != len(ent):
                fail("bad entity length in " + name)
        buckets[name] = [(e, cint(a), cint(b)) for e, _, a, b in rows]
    for tbl, rust_name, doc in (
        ("html5", "HTML5_NAMES", "HTML5 (`ent_ht_html5`)"),
        ("html4", "HTML4_NAMES", "HTML 4.01 (`ent_ht_html4`)"),
        ("be_noapos", "BASIC_NOAPOS_NAMES", "basic entities without `&apos;` (`ent_ht_be_noapos`)"),
        ("be_apos", "BASIC_APOS_NAMES", "basic entities with `&apos;` (`ent_ht_be_apos`)"),
    ):
        m = re.search(
            r"static const entity_ht ent_ht_%s = \{\s*(0x[0-9A-Fa-f]+),\s*ht_buckets_%s\s*\};" % (tbl, tbl),
            src,
        )
        num = cint(m.group(1))
        names = items(body_of(src, "static const entity_cp_map *const ht_buckets_%s[]" % tbl))
        if len(names) != num:
            fail("bucket count mismatch for " + tbl)
        entries = []
        for i, n in enumerate(names):
            for e in buckets[n]:
                if zend_inline_hash(e[0]) % num != i:
                    fail("entity %s is in the wrong bucket of %s" % (e[0], tbl))
                entries.append(e)
        entries.sort(key=lambda e: e[0].encode("ascii"))
        if len({e[0] for e in entries}) != len(entries):
            fail("duplicate entity in " + tbl)
        if max(len(e[0]) for e in entries) > longest_entity:
            fail("entity longer than LONGEST_ENTITY_LENGTH in " + tbl)
        w("/// Entity -> code point(s) for %s, sorted by name." % doc)
        w("pub static %s: [NamedEntity; %d] = [" % (rust_name, len(entries)))
        for e, a, b in entries:
            w("    (%s, 0x%05X, 0x%05X)," % (rust_str(e), a, b))
        w("];")
        w("")

    sys.stdout.write("\n".join(out).rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
