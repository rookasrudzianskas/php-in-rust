pub fn mb_wchar_to_8859_1(input: &[u32], buf: &mut ConvertBuf, _end: bool) {
    for &w in input {
        if w < 0x100 {
            buf.add(w as u8);
        } else {
            mb_illegal_output(w, mb_wchar_to_8859_1, buf);
        }
    }
}

pub fn mb_cp1252_to_wchar(input: &mut &[u8], out: &mut [u32], _state: &mut u32) -> usize {
    let n = input.len().min(out.len());
    for (o, &c) in out.iter_mut().zip(&input[..n]) {
        *o = if (0x80..0xA0).contains(&c) {
            coalesce(CP1252_UCS_TABLE[(c - 0x80) as usize] as u32, BAD_INPUT)
        } else {
            c as u32
        };
    }
    *input = &input[n..];
    n
}

pub fn mb_wchar_to_cp1252(input: &[u32], buf: &mut ConvertBuf, _end: bool) {
    for &w in input {
        if w >= 0x100 {
            match CP1252_UCS_TABLE.iter().position(|&t| t as u32 == w) {
                Some(i) => buf.add(i as u8 + 0x80),
                None => mb_illegal_output(w, mb_wchar_to_cp1252, buf),
            }
        } else if w <= 0x7F || w >= 0xA0 || matches!(w, 0x81 | 0x8D | 0x8F | 0x90 | 0x9D) {
            buf.add(w as u8);
        } else {
            mb_illegal_output(w, mb_wchar_to_cp1252, buf);
        }
    }
}

pub fn mb_armscii8_to_wchar(input: &mut &[u8], out: &mut [u32], _state: &mut u32) -> usize {
    let n = input.len().min(out.len());
    for (o, &c) in out.iter_mut().zip(&input[..n]) {
        *o = if c < 0xA0 {
            c as u32
        } else {
            coalesce(ARMSCII8_UCS_TABLE[(c - 0xA0) as usize] as u32, BAD_INPUT)
        };
    }
    *input = &input[n..];
    n
}

pub fn mb_wchar_to_armscii8(input: &[u32], buf: &mut ConvertBuf, _end: bool) {
    for &w in input {
        if (0x28..=0x2F).contains(&w) {
            buf.add(UCS_ARMSCII8_TABLE[(w - 0x28) as usize]);
        } else if w < 0xA0 {
            buf.add(w as u8);
        } else {
            match ARMSCII8_UCS_TABLE.iter().position(|&t| t as u32 == w) {
                Some(i) => buf.add(0xA0 + i as u8),
                None => mb_illegal_output(w, mb_wchar_to_armscii8, buf),
            }
        }
    }
}

